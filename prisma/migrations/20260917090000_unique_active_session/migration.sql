-- ============================================================
-- منع تعدد الجلسات لنفس الشخص في نفس اللحظة
-- فهرس جزئي فريد: لا يسمح إلا بجلسة واحدة 'active' لكل student_id.
-- أي محاولة إدراج ثانية لجلسة نشطة لنفس الطالب تُرفض على مستوى
-- قاعدة البيانات (خطأ SQLSTATE 23505) مهما حدث التزامن.
-- ============================================================
CREATE UNIQUE INDEX IF NOT EXISTS sessions_active_student_idx
  ON public.sessions (student_id)
  WHERE status = 'active';